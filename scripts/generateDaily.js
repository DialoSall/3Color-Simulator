import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dailyBankConfig as config } from "../src/data/daily/config.js";
import { handcraftedPuzzles } from "../src/data/daily/handcrafted.js";
import { historicalSchedule } from "../src/data/daily/history.js";
import { addDailyDays } from "../src/utils/dailyDate.js";
import { calibrateDaily } from "./lib/dailyCalibration.js";
import { generateCandidate } from "./lib/dailyCandidate.js";
import { seededRandom, shuffle } from "./lib/dailyGraph.js";
import { createLedger } from "./lib/dailyIntegrity.js";
import { validateDailyPuzzle } from "./lib/dailyValidation.js";

const root = new URL('../', import.meta.url);
const checking = process.argv.includes('--check');
const calibration = calibrateDaily();
const targets = shuffle(Object.entries(config.difficultyCounts).flatMap(([name,count])=>Array(count).fill(name)), seededRandom(config.seed));
if (targets.length !== config.days) throw new Error('Difficulty quotas do not match coverage.');
const signatures = new Set();
const bank = [];
let attempted = 0;
for (let day = 0; day < config.days; day++) {
  const dateKey = addDailyDays(config.rolloutDate, day);
  let accepted;
  for (let candidate = 0; candidate < 20000; candidate++) {
    attempted++;
    const seed = `${config.seed}:${dateKey}:${candidate}`;
    const graph = generateCandidate(seed, calibration);
    if (!graph || graph.difficulty !== targets[day] || signatures.has(graph.signature)) continue;
    const { signature, ...data } = graph;
    accepted = {id: `daily-${dateKey}-v${config.generatorVersion}`, dateKey, version: 1,
      name: `${graph.difficulty} Daily`, description: 'Color every circle so connected circles have different colors.',
      source: 'generated', ...data, generation: {version: config.generatorVersion, seed, candidate},
    };
    const errors = validateDailyPuzzle(accepted, {calibration});
    if (errors.length) throw new Error(`${dateKey}: ${errors.join(' ')}`);
    signatures.add(signature);
    break;
  }
  if (!accepted) throw new Error(`No quality candidate found for ${dateKey}; bank was not written.`);
  bank.push(accepted);
}
const groups = new Map();
for (const puzzle of bank) {
  const month = puzzle.dateKey.slice(0,7);
  if (!groups.has(month)) groups.set(month, []);
  groups.get(month).push(puzzle);
}
const outputs = new Map();
for (const [month,puzzles] of groups) outputs.set(`src/data/daily/generated/${month}.js`, `// Generated by npm run generate:daily. Frozen puzzle data; do not edit.\nexport default [\n${puzzles.map(puzzle=>`  ${JSON.stringify(puzzle)},`).join('\n')}\n];\n`);
outputs.set('src/data/daily/generated/index.js', [...groups.keys()].map((month,index)=>`import month${index} from "./${month}.js";`).join('\n') + `\nexport const generatedDailyPuzzles = [${[...groups.keys()].map((_,index)=>`...month${index}`).join(', ')}];\n`);
outputs.set('src/data/daily/calibration.json', JSON.stringify({...calibration, range:{start:config.rolloutDate,end:addDailyDays(config.rolloutDate,config.days-1)},counts:config.difficultyCounts,candidatesExamined:attempted},null,2)+'\n');
// Existing bank files are immutable. Reproduction checks never write; future
// handcrafted replacements are handled by the separate scheduling command.
for (const [path,content] of outputs) {
  let previous;
  try { previous = await readFile(new URL(path,root),'utf8'); } catch(error) {if(error.code!=='ENOENT')throw error;}
  if (previous !== undefined && previous !== content) throw new Error(`${path} differs from deterministic output. Refusing to overwrite frozen data.`);
  if (checking && previous !== content) throw new Error(`Missing generated file: ${path}`);
}
if (!checking) {
  await mkdir(new URL('src/data/daily/generated/',root),{recursive:true});
  for (const [path,content] of outputs) await writeFile(new URL(path,root),content);
  const ledgerPath = new URL('src/data/daily/integrity.json',root);
  let exists = true;
  try {await readFile(ledgerPath);} catch(error) {if(error.code==='ENOENT')exists=false;else throw error;}
  if (!exists) {
    const schedule = {...historicalSchedule,...Object.fromEntries(bank.map(puzzle=>[puzzle.dateKey,puzzle.id]))};
    await writeFile(ledgerPath,JSON.stringify(createLedger([...handcraftedPuzzles,...bank],schedule),null,2)+'\n');
  }
}
console.log(`${checking?'Reproduced':'Generated'} ${bank.length} puzzles: ${config.rolloutDate} – ${bank.at(-1).dateKey}.`);
console.log(JSON.stringify({counts:config.difficultyCounts,candidatesExamined:attempted,bands:calibration.bands}));
